CATALOG = {"en": EN, "tr": TR}


class Lang:
    """Callable translator: `L("plugged", time="18:13", amps=32, mode="charge now")`."""

    def __init__(self, code: str = "en"):
        self.set(code)

    def set(self, code: str) -> None:
        self.code = code if code in CATALOG else "en"
        self.d = CATALOG[self.code]

    def has(self, key: str) -> bool:
        return key in self.d or key in EN

    def __call__(self, key: str, **kw) -> str:
        text = self.d.get(key) or EN.get(key) or key
        try:
            return text.format(**kw) if kw else text
        except (KeyError, IndexError):
            return text
